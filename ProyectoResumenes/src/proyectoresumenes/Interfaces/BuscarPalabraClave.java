    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        try {
            String palabra = this.entrada.getText();
            Sistema sistema = new Sistema(avlA, avlPC, tablahash);

            Lista listaPC = sistema.buscarPorPalabraClave(palabra);

            String[] titulos = listaPC.obtenerTitulos();
            if (titulos.length == 0) {
                JOptionPane.showMessageDialog(rootPane, "No se encontraron resumenes para el autor");
            }

            Sistema.ordenaraALFABETICO(titulos);

            for (String titulo : titulos) {
                this.opciones.addItem(titulo);
            }
        } catch (Exception e) {

        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {
            String titulo = this.opciones.getSelectedItem().toString();
            Sistema sistema = new Sistema(avlA, avlPC, tablahash);

            Resumen rAnalizar = sistema.buscarResumenPorTitulo(titulo);

            if (rAnalizar != null) {

                PalabraFrecuencia[] frecuencias = sistema.analizarResumen(rAnalizar);
                Sistema.ordenarfrFRECUENCIAS(frecuencias);
                this.salida.setText(rAnalizar.analizar());
                for (int i = 0; i < frecuencias.length; i++) {
                    PalabraFrecuencia pf = frecuencias[i];
                    if (pf.frecuencia > 0) {
                        this.salida.setText(this.salida.getText() + "  - " + pf.palabra + ": " + pf.frecuencia + " veces\n");
                    }
                }
                this.salida.setText("\nCuerpo: \n" + rAnalizar.cuerpo);
            } else {
                JOptionPane.showMessageDialog(rootPane, "Resumen no encontrado");
            }
        } catch (Exception e) {

        }
    }//GEN-LAST:event_jButton2ActionPerformed

